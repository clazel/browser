//! Writing the resolved model as Rust data: one value of
//! `crates/clazel-webidl/src/model.rs`'s types per definition, in `static`
//! tables sorted by name.
//!
//! The files are written in a fixed layout (one list element per line, no
//! dependence on a formatter), so `check` compares them byte for byte; the
//! module that includes them is marked `#[rustfmt::skip]`.

use std::fmt::Write as _;

use super::model::{
    Argument, Attribute, Collection, Const, DictMember, ExtAttr, ExtValue, Iterable, Member,
    MemberKind, OpKind, Operation, Simple, Ty, TyKind, Value,
};
use super::resolve::{Callback, Dictionary, EXTERNAL, Enum, Interface, Model, Namespace, Typedef};

/// What the header of every generated file says.
const HEADER: &str = "\
// @generated by `cargo xtask bindings` (xtask/src/bindings/) from
// crates/clazel-webidl/tests/data/webref-idl/ (the webref commit and the
// license are in SOURCE.md there). Do not edit: `cargo xtask check` fails if
// this differs from what the generator produces.
//
// What the generator derives (xtask/src/bindings/resolve.rs has the rules):
// - Every .idl file of that directory is parsed with our own parser, which
//   follows the grammar of WebIDL §2; the definitions of all files are
//   merged into one model.
// - Partial interfaces, dictionaries and namespaces are appended to their
//   target, in file order (files sorted by name), then source order.
// - `A includes M;` appends M's members (and its partials') to A, each
//   marked with the mixin's name.
// - `Exposed` and `SecureContext` written on a partial interface or on a
//   mixin are copied onto the members it adds, unless a member has its own.
// - Definitions are sorted by name. A mixin has no table of its own: its
//   members are in its includers.
// - A name that no vendored file defines is accepted only if it is in
//   xtask/src/bindings/resolve.rs's EXTERNAL list; those are in EXTERNAL
//   below, with no definition.
";

fn q(s: &str) -> String {
    format!("{s:?}")
}

fn opt_str(s: Option<&str>) -> String {
    s.map_or_else(|| "None".to_owned(), |s| format!("Some({})", q(s)))
}

fn simple(s: Simple) -> &'static str {
    match s {
        Simple::Any => "Any",
        Simple::Undefined => "Undefined",
        Simple::Boolean => "Boolean",
        Simple::Byte => "Byte",
        Simple::Octet => "Octet",
        Simple::Bigint => "Bigint",
        Simple::Object => "Object",
        Simple::Symbol => "Symbol",
        Simple::Short => "Short",
        Simple::UnsignedShort => "UnsignedShort",
        Simple::Long => "Long",
        Simple::UnsignedLong => "UnsignedLong",
        Simple::LongLong => "LongLong",
        Simple::UnsignedLongLong => "UnsignedLongLong",
        Simple::Float => "Float",
        Simple::UnrestrictedFloat => "UnrestrictedFloat",
        Simple::Double => "Double",
        Simple::UnrestrictedDouble => "UnrestrictedDouble",
        Simple::ByteString => "ByteString",
        Simple::DomString => "DomString",
        Simple::UsvString => "UsvString",
    }
}

fn value(v: &Value) -> String {
    match v {
        Value::Bool(b) => format!("Value::Bool({b})"),
        Value::Integer(n) => format!("Value::Integer({n})"),
        Value::Decimal(s) => format!("Value::Decimal({})", q(s)),
        Value::Infinity => "Value::Infinity".to_owned(),
        Value::NegInfinity => "Value::NegInfinity".to_owned(),
        Value::NaN => "Value::NaN".to_owned(),
        Value::Str(s) => format!("Value::Str({})", q(s)),
        Value::EmptySequence => "Value::EmptySequence".to_owned(),
        Value::EmptyDictionary => "Value::EmptyDictionary".to_owned(),
        Value::Null => "Value::Null".to_owned(),
        Value::Undefined => "Value::Undefined".to_owned(),
    }
}

fn opt_value(v: Option<&Value>) -> String {
    v.map_or_else(|| "None".to_owned(), |v| format!("Some({})", value(v)))
}

fn list<T>(items: &[T], f: impl Fn(&T) -> String) -> String {
    let parts: Vec<String> = items.iter().map(f).collect();
    format!("&[{}]", parts.join(", "))
}

fn ext_value(v: &ExtValue) -> String {
    match v {
        ExtValue::None => "ExtValue::None".to_owned(),
        ExtValue::Ident(s) => format!("ExtValue::Ident({})", q(s)),
        ExtValue::IdentList(l) => format!("ExtValue::IdentList({})", list(l, |s| q(s))),
        ExtValue::Wildcard => "ExtValue::Wildcard".to_owned(),
        ExtValue::Literal(v) => format!("ExtValue::Literal({})", value(v)),
        ExtValue::LiteralList(l) => format!("ExtValue::LiteralList({})", list(l, value)),
        ExtValue::Args(a) => format!("ExtValue::Args({})", args(a)),
        ExtValue::NamedArgs(n, a) => format!("ExtValue::NamedArgs({}, {})", q(n), args(a)),
    }
}

fn ext(attrs: &[ExtAttr]) -> String {
    list(attrs, |a| {
        format!(
            "ExtAttr {{ name: {}, value: {} }}",
            q(&a.name),
            ext_value(&a.value)
        )
    })
}

fn kind(k: &TyKind) -> String {
    let boxed = |t: &Ty| format!("&{}", ty(t));
    match k {
        TyKind::Simple(s) => format!("Type::Simple(Simple::{})", simple(*s)),
        TyKind::Buffer(n) => format!("Type::Buffer({})", q(n)),
        TyKind::Named(n) => format!("Type::Named({})", q(n)),
        TyKind::Sequence(t) => format!("Type::Sequence({})", boxed(t)),
        TyKind::FrozenArray(t) => format!("Type::FrozenArray({})", boxed(t)),
        TyKind::ObservableArray(t) => format!("Type::ObservableArray({})", boxed(t)),
        TyKind::Record(k, v) => format!("Type::Record({}, {})", boxed(k), boxed(v)),
        TyKind::Promise(t) => format!("Type::Promise({})", boxed(t)),
        TyKind::Union(ts) => format!("Type::Union({})", list(ts, ty)),
    }
}

fn ty(t: &Ty) -> String {
    format!(
        "TypeRef {{ ty: {}, nullable: {}, ext_attrs: {} }}",
        kind(&t.kind),
        t.nullable,
        ext(&t.ext)
    )
}

fn opt_ty(t: Option<&Ty>) -> String {
    t.map_or_else(|| "None".to_owned(), |t| format!("Some({})", ty(t)))
}

fn arg(a: &Argument) -> String {
    format!(
        "Argument {{ name: {}, ty: {}, optional: {}, variadic: {}, default: {}, ext_attrs: {} }}",
        q(&a.name),
        ty(&a.ty),
        a.optional,
        a.variadic,
        opt_value(a.default.as_ref()),
        ext(&a.ext)
    )
}

fn args(a: &[Argument]) -> String {
    list(a, arg)
}

fn constant(c: &Const, m: &Member) -> String {
    format!(
        "Constant {{ name: {}, ty: {}, value: {}, mixin: {}, ext_attrs: {} }}",
        q(&c.name),
        ty(&c.ty),
        value(&c.value),
        opt_str(m.mixin.as_deref()),
        ext(&m.ext)
    )
}

fn attribute(a: &Attribute, m: &Member) -> String {
    format!(
        "Attribute {{ name: {}, ty: {}, readonly: {}, inherit: {}, is_static: {}, stringifier: {}, mixin: {}, ext_attrs: {} }}",
        q(&a.name),
        ty(&a.ty),
        a.readonly,
        a.inherit,
        a.is_static,
        a.stringifier,
        opt_str(m.mixin.as_deref()),
        ext(&m.ext)
    )
}

fn operation(o: &Operation, m: &Member) -> String {
    let kind = match o.kind {
        OpKind::Regular => "Regular",
        OpKind::Static => "Static",
        OpKind::Getter => "Getter",
        OpKind::Setter => "Setter",
        OpKind::Deleter => "Deleter",
        OpKind::Stringifier => "Stringifier",
    };
    format!(
        "Operation {{ name: {}, kind: OperationKind::{kind}, ret: {}, args: {}, mixin: {}, ext_attrs: {} }}",
        opt_str(o.name.as_deref()),
        ty(&o.ret),
        args(&o.args),
        opt_str(m.mixin.as_deref()),
        ext(&m.ext)
    )
}

fn iterable(i: &Iterable, m: &Member) -> String {
    format!(
        "Some(Iterable {{ is_async: {}, key: {}, value: {}, args: {}, ext_attrs: {} }})",
        i.is_async,
        opt_ty(i.key.as_ref()),
        ty(&i.value),
        args(&i.args),
        ext(&m.ext)
    )
}

fn collection(c: &Collection, m: &Member) -> String {
    format!(
        "Some(Collection {{ is_map: {}, readonly: {}, key: {}, value: {}, ext_attrs: {} }})",
        c.is_map,
        c.readonly,
        opt_ty(c.key.as_ref()),
        ty(&c.value),
        ext(&m.ext)
    )
}

/// The members of one kind, each as an element on its own line, indented.
fn elements<T>(items: impl Iterator<Item = T>, f: impl Fn(T) -> String, indent: &str) -> String {
    let lines: Vec<String> = items.map(|i| format!("{indent}    {},\n", f(i))).collect();
    if lines.is_empty() {
        "&[]".to_owned()
    } else {
        format!("&[\n{}{indent}]", lines.concat())
    }
}

fn consts(members: &[Member], indent: &str) -> String {
    let it = members.iter().filter_map(|m| match &m.kind {
        MemberKind::Const(c) => Some((c, m)),
        _ => None,
    });
    elements(it, |(c, m)| constant(c, m), indent)
}

fn attributes(members: &[Member], indent: &str) -> String {
    let it = members.iter().filter_map(|m| match &m.kind {
        MemberKind::Attribute(a) => Some((a, m)),
        _ => None,
    });
    elements(it, |(a, m)| attribute(a, m), indent)
}

fn operations(members: &[Member], indent: &str) -> String {
    let it = members.iter().filter_map(|m| match &m.kind {
        MemberKind::Operation(o) => Some((o, m)),
        _ => None,
    });
    elements(it, |(o, m)| operation(o, m), indent)
}

fn interface_text(i: &Interface) -> String {
    let constructors = elements(
        i.members.iter().filter_map(|m| match &m.kind {
            MemberKind::Constructor(a) => Some((a, m)),
            _ => None,
        }),
        |(a, m)| {
            format!(
                "Constructor {{ args: {}, ext_attrs: {} }}",
                args(a),
                ext(&m.ext)
            )
        },
        "        ",
    );
    let it = i
        .members
        .iter()
        .find_map(|m| match &m.kind {
            MemberKind::Iterable(x) => Some(iterable(x, m)),
            _ => None,
        })
        .unwrap_or_else(|| "None".to_owned());
    let col = i
        .members
        .iter()
        .find_map(|m| match &m.kind {
            MemberKind::Collection(x) => Some(collection(x, m)),
            _ => None,
        })
        .unwrap_or_else(|| "None".to_owned());
    format!(
        "    Interface {{\n        name: {},\n        parent: {},\n        callback: {},\n        ext_attrs: {},\n        includes: {},\n        constructors: {constructors},\n        constants: {},\n        attributes: {},\n        operations: {},\n        iterable: {it},\n        collection: {col},\n    }},\n",
        q(&i.name),
        opt_str(i.parent.as_deref()),
        i.callback,
        ext(&i.ext),
        list(&i.includes, |s| q(s)),
        consts(&i.members, "        "),
        attributes(&i.members, "        "),
        operations(&i.members, "        "),
    )
}

fn namespace_text(n: &Namespace) -> String {
    format!(
        "    Namespace {{\n        name: {},\n        ext_attrs: {},\n        constants: {},\n        attributes: {},\n        operations: {},\n    }},\n",
        q(&n.name),
        ext(&n.ext),
        consts(&n.members, "        "),
        attributes(&n.members, "        "),
        operations(&n.members, "        "),
    )
}

fn dict_member(m: &DictMember) -> String {
    format!(
        "DictionaryMember {{ name: {}, ty: {}, required: {}, default: {}, ext_attrs: {} }}",
        q(&m.name),
        ty(&m.ty),
        m.required,
        opt_value(m.default.as_ref()),
        ext(&m.ext)
    )
}

fn dictionary_text(d: &Dictionary) -> String {
    format!(
        "    Dictionary {{\n        name: {},\n        parent: {},\n        ext_attrs: {},\n        members: {},\n    }},\n",
        q(&d.name),
        opt_str(d.parent.as_deref()),
        ext(&d.ext),
        elements(d.members.iter(), dict_member, "        "),
    )
}

fn enum_text(e: &Enum) -> String {
    format!(
        "    Enumeration {{ name: {}, ext_attrs: {}, values: {} }},\n",
        q(&e.name),
        ext(&e.ext),
        list(&e.values, |s| q(s))
    )
}

fn typedef_text(t: &Typedef) -> String {
    format!(
        "    Typedef {{ name: {}, ext_attrs: {}, ty: {} }},\n",
        q(&t.name),
        ext(&t.ext),
        ty(&t.ty)
    )
}

fn callback_text(c: &Callback) -> String {
    format!(
        "    Callback {{ name: {}, ext_attrs: {}, ret: {}, args: {} }},\n",
        q(&c.name),
        ext(&c.ext),
        ty(&c.ret),
        args(&c.args)
    )
}

/// One table file: header, doc line, import, the `static`.
fn table<T>(doc: &str, name: &str, ty_name: &str, items: &[T], f: impl Fn(&T) -> String) -> String {
    let mut out = String::new();
    out.push_str(HEADER);
    let _ = writeln!(out, "\n//! {doc}\n");
    out.push_str("use crate::model::*;\n\n");
    let _ = writeln!(out, "/// {doc}");
    let _ = writeln!(out, "pub static {name}: &[{ty_name}] = &[");
    for i in items {
        out.push_str(&f(i));
    }
    out.push_str("];\n");
    out
}

/// The generated files: (file name, text), in the order written.
pub fn files(m: &Model) -> Vec<(String, String)> {
    let mut mod_rs = String::new();
    mod_rs.push_str("//! The resolved interface model of the vendored WebIDL (item 7.12): plain data of\n//! the types in [`crate::model`], one table per kind of definition, sorted by name.\n//!\n");
    for l in HEADER.lines() {
        let _ = writeln!(mod_rs, "{}", l.trim_end());
    }
    mod_rs.push_str("\nuse crate::model::{External, ForeignIncludes};\n\npub mod bindings;\n");
    for (module, table) in [
        ("callbacks", "CALLBACKS"),
        ("dictionaries", "DICTIONARIES"),
        ("enums", "ENUMS"),
        ("interfaces", "INTERFACES"),
        ("namespaces", "NAMESPACES"),
        ("typedefs", "TYPEDEFS"),
    ] {
        let _ = writeln!(mod_rs, "mod {module};");
        let _ = writeln!(mod_rs, "pub use {module}::{table};");
    }
    mod_rs.push_str("\n/// Names the IDL refers to that no vendored file defines, with the standard that does.\n/// They have no entry in any table. Only the names the files use are listed.\npub static EXTERNAL: &[External] = &[\n");
    for (name, by) in EXTERNAL {
        if m.external.iter().any(|n| n == name) {
            let _ = writeln!(
                mod_rs,
                "    External {{ name: {}, defined_by: {} }},",
                q(name),
                q(by)
            );
        }
    }
    mod_rs.push_str("];\n\n/// `includes` statements whose interface is in [`EXTERNAL`]; the interface is not in\n/// [`INTERFACES`], so its members from these mixins are not in the model.\npub static FOREIGN_INCLUDES: &[ForeignIncludes] = &[\n");
    for (i, mix) in &m.foreign_includes {
        let _ = writeln!(
            mod_rs,
            "    ForeignIncludes {{ interface: {}, mixin: {} }},",
            q(i),
            q(mix)
        );
    }
    mod_rs.push_str("];\n");
    vec![
        ("mod.rs".to_owned(), mod_rs),
        ("bindings.rs".to_owned(), super::glue::emit(m, HEADER)),
        (
            "interfaces.rs".to_owned(),
            table(
                "Interfaces and callback interfaces, sorted by name.",
                "INTERFACES",
                "Interface",
                &m.interfaces,
                interface_text,
            ),
        ),
        (
            "namespaces.rs".to_owned(),
            table(
                "Namespaces, sorted by name.",
                "NAMESPACES",
                "Namespace",
                &m.namespaces,
                namespace_text,
            ),
        ),
        (
            "dictionaries.rs".to_owned(),
            table(
                "Dictionaries, sorted by name.",
                "DICTIONARIES",
                "Dictionary",
                &m.dictionaries,
                dictionary_text,
            ),
        ),
        (
            "enums.rs".to_owned(),
            table(
                "Enums, sorted by name.",
                "ENUMS",
                "Enumeration",
                &m.enums,
                enum_text,
            ),
        ),
        (
            "typedefs.rs".to_owned(),
            table(
                "Typedefs, sorted by name.",
                "TYPEDEFS",
                "Typedef",
                &m.typedefs,
                typedef_text,
            ),
        ),
        (
            "callbacks.rs".to_owned(),
            table(
                "Callback function types, sorted by name.",
                "CALLBACKS",
                "Callback",
                &m.callbacks,
                callback_text,
            ),
        ),
    ]
}

/// The counts, for the notes of a run.
pub fn summary(m: &Model) -> String {
    let count = |f: &dyn Fn(&Member) -> bool| -> usize {
        m.interfaces
            .iter()
            .flat_map(|i| &i.members)
            .chain(m.namespaces.iter().flat_map(|n| &n.members))
            .filter(|x| f(x))
            .count()
    };
    let callback_interfaces = m.interfaces.iter().filter(|i| i.callback).count();
    format!(
        "{} interfaces ({} callback interfaces), {} mixins resolved into their includers, {} namespaces, {} dictionaries with {} members, {} enums with {} values, {} typedefs, {} callbacks; \
         interface and namespace members: {} attributes, {} operations, {} constants, {} constructors, {} iterables, {} maplikes and setlikes; {} external names",
        m.interfaces.len(),
        callback_interfaces,
        m.mixins,
        m.namespaces.len(),
        m.dictionaries.len(),
        m.dictionaries
            .iter()
            .map(|d| d.members.len())
            .sum::<usize>(),
        m.enums.len(),
        m.enums.iter().map(|e| e.values.len()).sum::<usize>(),
        m.typedefs.len(),
        m.callbacks.len(),
        count(&|x| matches!(x.kind, MemberKind::Attribute(_))),
        count(&|x| matches!(x.kind, MemberKind::Operation(_))),
        count(&|x| matches!(x.kind, MemberKind::Const(_))),
        count(&|x| matches!(x.kind, MemberKind::Constructor(_))),
        count(&|x| matches!(x.kind, MemberKind::Iterable(_))),
        count(&|x| matches!(x.kind, MemberKind::Collection(_))),
        m.external.len(),
    )
}
