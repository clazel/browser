#[test]
fn scripts_that_parse() {
    let mut failed = Vec::new();
    for s in SCRIPT_OK {
        if !accepted(s, SourceGoal::Script) {
            failed.push(*s);
        }
    }
    assert!(failed.is_empty(), "should parse as a Script:\n{}", failed.join("\n---\n"));
}

#[test]
fn scripts_that_do_not_parse() {
    let mut failed = Vec::new();
    for s in SCRIPT_BAD {
        if accepted(s, SourceGoal::Script) {
            failed.push(*s);
        }
    }
    assert!(failed.is_empty(), "should not parse as a Script:\n{}", failed.join("\n---\n"));
}

