//! A corpus of small programs: what the parser must accept and reject. The
//! vendored Test262 has few positive tests of the syntax (its `expressions/` and
//! `statements/` directories are not vendored), so the grammar's coverage is
//! here.

use clazel_js_syntax::exec::parse;
use clazel_js_syntax::spec::SourceGoal;

fn cps(s: &str) -> Vec<u32> {
    s.chars().map(u32::from).collect()
}

fn accepted(s: &str, goal: SourceGoal) -> bool {
    parse(&cps(s), goal).is_ok()
}

