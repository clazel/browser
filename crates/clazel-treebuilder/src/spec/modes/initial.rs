//! HTML §13.2.6.4.1 the "initial" insertion mode, with the DOCTYPE
//! token's quirks and limited-quirks lists as data. The modelling choices
//! are listed in [`super::super`]; the ones this mode reads:
//! - the document is never an `iframe` `srcdoc` document and its "parser
//!   cannot change the mode flag" is false, so the conditions on them are
//!   true and are not written out;
//! - a DOCTYPE token's missing name or identifier is `None`; "missing" and
//!   "the empty string" are distinct, as the standard says;
//! - "compared … in an ASCII case-insensitive manner" applies to the system
//!   and public identifiers only (the standard's sentence names those); the
//!   name is compared exactly with "html" (the tokenizer lowercases it).

