//! The equivalence lemmas for foreign content: the W3C transcription
//! ([`super::foreign`], W3C HTML 5.2 §8.2.5.5 and the adjustment tables of
//! §8.2.5.2) and [`crate::spec`]'s (WHATWG §13.2.6.5,
//! `spec::modes::foreign` and `spec::base::tables`) give the same result on
//! every input where the two documents prescribe the same thing. Each
//! lemma's precondition excludes exactly the inputs where they differ, and
//! its doc comment says what the difference is.
//!
//! - The three tables (the SVG tag names, "adjust SVG attributes", "adjust
//!   foreign attributes") are equal on every name: the two documents have
//!   the same rows in the same order ([`lemma_svg_element_name`],
//!   [`lemma_svg_attribute_name`], [`lemma_foreign_attribute`]).
//! - The three attribute adjustments agree on a token's attributes (no
//!   namespace and no prefix, `attrs_plain`): the WHATWG transcription only
//!   adjusts attributes with no namespace, the W3C text every one.
//! - The rules ([`lemma_foreign_content`]) agree on every token the
//!   dispatcher sends to them, except: the WHATWG adds `menu` to the
//!   breakout start tags, and the end tags `br` and `p` as breakout end
//!   tags; the W3C's breakout entries have a fragment case (with a fragment
//!   context the token is handled as "any other start tag"), which the
//!   WHATWG text has dropped; and the WHATWG's processing instruction
//!   tokens (which the W3C does not have).

