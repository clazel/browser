//! with the algorithms of §8.2.5.2 it calls: "adjust MathML attributes",
//! "adjust SVG attributes" and "adjust foreign attributes", and the SVG tag
//! name table of its "any other start tag" entry. Source and modelling
//! choices: [`super`]. Specific to this section:
//! - The three tables and the tag name table are transcribed here, one spec
//!   function each, one branch per row in the W3C's order, the row quoted
//!   above it ([`w3c_svg_element_name`], [`w3c_svg_attribute_name`],
//!   [`w3c_foreign_attribute`]). A name not in the first column is left as
//!   it is (`None` for the foreign attributes).
//! - A token's attributes are DOM attributes with no namespace (as in
//!   [`crate::spec`]); "change its name" sets the attribute's local name, and
//!   "let the attribute be a namespaced attribute" sets its namespace,
//!   prefix and local name. An attribute matches a row when its local name is
//!   the row's string.
//! - "Change the tag name" changes the token's name and keeps its [`Tag`]:
//!   the one tag name of the table the rules mention (`foreignobject`) has
//!   the same [`Tag`] under both spellings (see [`crate::spec::base::tags`]),
//!   and every other renamed name has none.
//! - "Pop elements from the stack of open elements until node has been
//!   popped" keeps the entries below node's index: node is tracked by its
//!   index on the stack.
//! - "Process the token according to the rules given in the section
//!   corresponding to the current insertion mode in HTML content" is
//!   `Outcome::Reprocess(p, t)` (which is what that outcome means, see
//!   [`super`]).
//! - The SVG `script` end tag: the insertion point, the script nesting level
//!   and the parser pause flag are not modelled (see [`super`]), and
//!   "process the SVG script element according to the SVG rules" is handed
//!   to the driver as `Action::ScriptReady(node)`, as "prepare the script"
//!   is.
//! - The end-of-file token has no entry (the dispatcher never sends it here):
//!   ignored, as [`super`] says for a token without an entry.

