//! Examples of the log format, evaluated on [`super::spec`] by Verus
//! (`compute_only`), so the spec is checked against octets written out by
//! hand from the ASN.1 in its header. The check values were computed
//! separately with the textbook reflected CRC-32C (polynomial `0x82f63b78`
//! reversed, initial and final value `0xffffffff`), not with this crate.

#[allow(unused_imports)]
use super::spec::*;
#[allow(unused_imports)]
use vstd::prelude::*;

verus! {

/// INTEGERs: the shortest contents, with a zero octet in front of a first
/// octet with bit 8 set (X.690 §8.3.2).
pub proof fn example_numbers()
    ensures
        encode_number(0) == seq![0x02u8, 0x01, 0x00],
        encode_number(127) == seq![0x02u8, 0x01, 0x7f],
        encode_number(128) == seq![0x02u8, 0x02, 0x00, 0x80],
        encode_number(0xffff_ffff_ffff_ffff) == seq![0x02u8, 0x09, 0x00, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff],
{
    assert(encode_number(0) == seq![0x02u8, 0x01, 0x00]) by (compute_only);
    assert(encode_number(127) == seq![0x02u8, 0x01, 0x7f]) by (compute_only);
    assert(encode_number(128) == seq![0x02u8, 0x02, 0x00, 0x80]) by (compute_only);
    assert(encode_number(0xffff_ffff_ffff_ffff) == seq![
        0x02u8,
        0x09,
        0x00,
        0xff,
        0xff,
        0xff,
        0xff,
        0xff,
        0xff,
        0xff,
        0xff,
    ]) by (compute_only);
}

/// The header of bucket "id": `SEQUENCE { "clazel-store", 1, "id" }`.
pub proof fn example_header()
    ensures
        encode_header(seq![0x69u8, 0x64]) == seq![
            0x30u8, 0x15, 0x04, 0x0c, 0x63, 0x6c, 0x61, 0x7a, 0x65, 0x6c, 0x2d, 0x73, 0x74, 0x6f, 0x72,
            0x65, 0x02, 0x01, 0x01, 0x04, 0x02, 0x69, 0x64,
        ],
{
    assert(encode_header(seq![0x69u8, 0x64]) == seq![
        0x30u8, 0x15, 0x04, 0x0c, 0x63, 0x6c, 0x61, 0x7a, 0x65, 0x6c, 0x2d, 0x73, 0x74, 0x6f, 0x72,
        0x65, 0x02, 0x01, 0x01, 0x04, 0x02, 0x69, 0x64,
    ]) by (compute_only);
}

/// Commit 1 with no operations: `SEQUENCE { 1, {}, check }`.
pub proof fn example_empty_record()
    ensures
        encode_record(1, seq![]) == seq![
            0x30u8, 0x0b, 0x02, 0x01, 0x01, 0x30, 0x00, 0x04, 0x04, 0x28, 0x83, 0x1a, 0x0d,
        ],
{
    reveal(vstd::arithmetic::power::pow);
    assert(encode_record(1, seq![]) == seq![
        0x30u8, 0x0b, 0x02, 0x01, 0x01, 0x30, 0x00, 0x04, 0x04, 0x28, 0x83, 0x1a, 0x0d,
    ]) by (compute_only);
}

/// Commit 1 clearing bottle 0: `clear [2] { 0 }`.
pub proof fn example_clear_record()
    ensures
        encode_record(1, seq![Op::Clear { bottle: 0 }]) == seq![
            0x30u8, 0x10, 0x02, 0x01, 0x01, 0x30, 0x05, 0xa2, 0x03, 0x02, 0x01, 0x00, 0x04, 0x04,
            0xda, 0x03, 0x9d, 0x0a,
        ],
{
    reveal(vstd::arithmetic::power::pow);
    assert(encode_record(1, seq![Op::Clear { bottle: 0 }]) == seq![
        0x30u8, 0x10, 0x02, 0x01, 0x01, 0x30, 0x05, 0xa2, 0x03, 0x02, 0x01, 0x00, 0x04, 0x04,
        0xda, 0x03, 0x9d, 0x0a,
    ]) by (compute_only);
}

/// Commit 7 with one of each operation: `put [0] { 2, "k", "vv" }`,
/// `delete [1] { 128, "" }`, `clear [2] { 0 }`.
pub proof fn example_record()
    ensures
        encode_record(
            7,
            seq![
                Op::Put { bottle: 2, key: seq![0x6bu8], value: seq![0x76u8, 0x76] },
                Op::Delete { bottle: 128, key: seq![] },
                Op::Clear { bottle: 0 },
            ],
        ) == seq![
            0x30u8, 0x24, 0x02, 0x01, 0x07, 0x30, 0x19, 0xa0, 0x0a, 0x02, 0x01, 0x02, 0x04, 0x01,
            0x6b, 0x04, 0x02, 0x76, 0x76, 0xa1, 0x06, 0x02, 0x02, 0x00, 0x80, 0x04, 0x00, 0xa2,
            0x03, 0x02, 0x01, 0x00, 0x04, 0x04, 0x72, 0x18, 0x5d, 0x58,
        ],
{
    reveal(vstd::arithmetic::power::pow);
    assert(encode_record(
        7,
        seq![
            Op::Put { bottle: 2, key: seq![0x6bu8], value: seq![0x76u8, 0x76] },
            Op::Delete { bottle: 128, key: seq![] },
            Op::Clear { bottle: 0 },
        ],
    ) == seq![
        0x30u8, 0x24, 0x02, 0x01, 0x07, 0x30, 0x19, 0xa0, 0x0a, 0x02, 0x01, 0x02, 0x04, 0x01,
        0x6b, 0x04, 0x02, 0x76, 0x76, 0xa1, 0x06, 0x02, 0x02, 0x00, 0x80, 0x04, 0x00, 0xa2,
        0x03, 0x02, 0x01, 0x00, 0x04, 0x04, 0x72, 0x18, 0x5d, 0x58,
    ]) by (compute_only);
}

} // verus!
