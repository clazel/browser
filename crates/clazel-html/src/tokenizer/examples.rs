//! Inputs evaluated on the spec (69 of them): each lemma states the tokens
//! [`tokenize`] gives for one input, which Verus computes. Together they
//! pass through every state and most cases of each; they are what the
//! kill certificates of `mutations.json` contradict. The expected tokens
//! were produced by the exec tokenizer (proven equal to the spec), and
//! each was checked by reading it against the standard; html5lib-tests
//! covers the same ground from outside the project.
//!
//! This is a module of its own because Verus evaluates every `by
//! (compute_only)` assertion of a module it verifies, so a mutant that
//! breaks an example would otherwise fail every kill certificate placed
//! next to it. No input here has a named character reference: evaluating
//! the 2231-row table is beyond Verus's evaluator (see
//! `crate::charref::examples`, which evaluates it by blocks).

