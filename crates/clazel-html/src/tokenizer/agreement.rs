//! The two transcriptions evaluated on the same inputs: for each input of
//! [`super::examples`], Verus computes the tokens of the W3C HTML 5.2
//! transcription ([`super::independent`]) and of the living standard's
//! ([`super::spec`]) and proves them equal, or, where the two texts
//! differ, proves them different and says why.
//!
//! Of the 68 inputs compared, 57 give the same tokens and 11 differ, each
//! for one of two differences between the texts: processing instructions
//! (5 inputs), and W3C's decimal character reference multiplier (6
//! inputs). The other differences between the texts (W3C's character
//! reference end state and decimal character reference start state, the
//! living standard's ambiguous ampersand state) change the steps, not the
//! tokens, on every input compared.
//!
//! The general theorem, on every input of a stated domain, is
//! `super::equivalence::theorem_w3c_equivalent`; these comparisons also
//! cover inputs outside that domain (character references, `[CDATA[`).
//!
//! One input of `examples.rs` is not compared: `& &;` (`lemma_example_amp_alone`),
//! where W3C's character reference state looks `;` up in the named
//! character references table, which Verus's evaluator cannot read inside a
//! run.
//!
//! This is a module of its own for the reason `examples.rs` is.

