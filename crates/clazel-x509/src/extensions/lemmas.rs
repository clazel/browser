//! Concrete X.509 extension and SAN specification witnesses.

#[allow(unused_imports)]
use super::spec::*;
#[allow(unused_imports)]
use vstd::prelude::*;

verus! {

/// Duplicate id-ce-subjectAltName extension identifiers are rejected.
pub proof fn lemma_reject_duplicate_san_extensions()
    ensures parse_extensions(seq![
        0x30u8, 0x12,
        0x30, 0x07, 0x06, 0x03, 0x55, 0x1d, 0x11, 0x04, 0x00,
        0x30, 0x07, 0x06, 0x03, 0x55, 0x1d, 0x11, 0x04, 0x00,
    ]) is None
{
    assert(parse_extensions(seq![
        0x30u8, 0x12,
        0x30, 0x07, 0x06, 0x03, 0x55, 0x1d, 0x11, 0x04, 0x00,
        0x30, 0x07, 0x06, 0x03, 0x55, 0x1d, 0x11, 0x04, 0x00,
    ]) is None) by (compute_only);
}

/// subjectAltName iPAddress accepts only four or sixteen octets.
pub proof fn lemma_reject_one_octet_ip_address()
    ensures parse_subject_alt_name(seq![0x30u8, 0x03, 0x87, 0x01, 0x01]) is None
{
    assert(parse_subject_alt_name(seq![0x30u8, 0x03, 0x87, 0x01, 0x01]) is None) by (compute_only);
}

/// DER omits the critical BOOLEAN when its DEFAULT value is FALSE.
pub proof fn lemma_reject_explicit_default_false()
    ensures parse_extensions(seq![
        0x30u8, 0x0c, 0x30, 0x0a, 0x06, 0x03, 0x55, 0x1d, 0x11,
        0x01, 0x01, 0x00, 0x04, 0x00,
    ]) is None
{
    assert(parse_extensions(seq![
        0x30u8, 0x0c, 0x30, 0x0a, 0x06, 0x03, 0x55, 0x1d, 0x11,
        0x01, 0x01, 0x00, 0x04, 0x00,
    ]) is None) by (compute_only);
}

} // verus!
