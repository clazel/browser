//! Concrete witnesses for the RFC 5280 Name decoder's structural properties.

#[allow(unused_imports)]
use super::spec::*;
#[allow(unused_imports)]
use vstd::prelude::*;

verus! {

/// A DER SET OF containing CN(z) before CN(a) is out of X.690 §11.6 order.
pub proof fn lemma_descending_rdn_attributes_are_rejected()
    ensures parse_name(seq![
        0x30u8, 0x16,
        0x31, 0x14,
        0x30, 0x08, 0x06, 0x03, 0x55, 0x04, 0x03, 0x0c, 0x01, b'z',
        0x30, 0x08, 0x06, 0x03, 0x55, 0x04, 0x03, 0x0c, 0x01, b'a',
    ]).is_none()
{
    assert(parse_name(seq![
        0x30u8, 0x16,
        0x31, 0x14,
        0x30, 0x08, 0x06, 0x03, 0x55, 0x04, 0x03, 0x0c, 0x01, b'z',
        0x30, 0x08, 0x06, 0x03, 0x55, 0x04, 0x03, 0x0c, 0x01, b'a',
    ]).is_none()) by (compute_only);
}

} // verus!
