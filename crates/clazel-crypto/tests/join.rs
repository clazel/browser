fn auth_for(host: Host, now: u64) -> Result<Auth, String> {
    let crypto = Sha256Suite;
    let mut transcript =
        Transcript::new(b"client hello").map_err(|error| format!("transcript: {error:?}"))?;
    transcript
        .push(&crypto, Kind::ServerHello, b"server hello")
        .map_err(|error| format!("transcript: {error:?}"))?;
    let config = Config {
        host,
        now,
        server_secret: vec![0x31; 32],
        client_secret: vec![0x42; 32],
        signatures: vec![0x0403, 0x0804],
        extensions: vec![0, 13],
    };
    Auth::start(config, transcript).map_err(|alert| format!("auth start alert {alert}"))
}

/// EncryptedExtensions, then this Certificate body: the action and phase.
fn certificate_step(
    verifier: &ChainVerifier<'_>,
    host: Host,
    now: u64,
    certificate: &[u8],
) -> Result<(Action, Phase), String> {
    let crypto = Sha256Suite;
    let mut auth = auth_for(host, now)?;
    let mut ee = Vec::new();
    write_encrypted_extensions(&mut ee, &[]);
    assert_eq!(
        auth.step(&crypto, verifier, Input::Handshake(8, &ee)),
        Action::None
    );
    let action = auth.step(&crypto, verifier, Input::Handshake(11, certificate));
    Ok((action, auth.phase()))
}

#[test]
#[cfg_attr(miri, ignore)]
fn the_handshake_runs_the_production_verifier() -> Result<(), String> {
    let production = mozilla();
    let c = case("online::google.com")?;
    let body = body_of(&presented(c)?);
    let now = limbo_now(c)?;
    // Accepted: the machine moves on to CertificateVerify.
    assert_eq!(
        certificate_step(&production, host_of(c)?, now, &body)?,
        (Action::None, Phase::CertificateVerify)
    );
    // RFC 8446 §6.2 bad_certificate (42): the wrong host.
    assert_eq!(
        certificate_step(&production, Host::Dns(b"example.com".to_vec()), now, &body)?,
        (Action::Fail(42), Phase::Failed)
    );
    // unknown_ca (48): an untrusted chain.
    assert_eq!(
        certificate_step(&ChainVerifier::new(&[]), host_of(c)?, now, &body)?,
        (Action::Fail(48), Phase::Failed)
    );
    // decode_error (50): an empty certificate_list, refused by the machine
    // before the verifier is asked (§4.4.2).
    assert_eq!(
        certificate_step(&production, host_of(c)?, now, &body_of(&[]))?,
        (Action::Fail(50), Phase::Failed)
    );
    // The production Verifier's other two functions: CertificateVerify by
    // `signature::exec::verify` (a garbage key verifies nothing) and the
    // timing-safe Finished comparison.
    assert!(!production.signature(b"not a key", 0x0403, b"input", b"signature"));
    assert!(production.finished_equal(&[7; 32], &[7; 32]));
    assert!(!production.finished_equal(&[7; 32], &[8; 32]));
    Ok(())
}
