//! The production chain validation (path-validation P16) end to end:
//! `clazel_crypto::join::exec::ChainVerifier`, the `clazel_tls`
//! `Verifier` that the authentication machine runs, on TLS Certificate
//! message bodies built from x509-limbo's chains.
//!
//! - **Real-world chains:** limbo's `online::*` testcases are chains
//!   collected from public servers (limbo's `SOURCE.md`, vendored in
//!   clazel-x509's `tests/data/x509-limbo/`). They are validated here
//!   against the production anchors, Mozilla's 118 server roots
//!   (`join::exec::mozilla`), at limbo's validation time.
//! - **Hostile chains:** an empty `certificate_list`, a garbage entry, a
//!   body that is not a Certificate, the wrong host, an expired leaf, an
//!   untrusted root, a missing intermediate, a cross-signed path, and an IP
//!   host against an iPAddress SAN and against a dNSName SAN. Each refusal
//!   is checked to give the `CertificateError` (and so the RFC 8446 §6.2
//!   alert) of `join::spec::certificate_error`.
//! - **Through the authentication machine:** `clazel_tls::auth::exec::Auth`
//!   with `Sha256Suite` and the production verifier accepts a real chain
//!   (and moves to CertificateVerify) and sends the expected alert for a
//!   wrong host, an untrusted chain and an empty list.

use clazel_crypto::join::exec::{ChainVerifier, Root, mozilla};
use clazel_crypto::provider::Sha256Suite;
use clazel_tls::auth::exec::{Action, Auth, Config, Input};
use clazel_tls::auth::spec::{CertificateError, Phase};
use clazel_tls::auth::verify::Verifier;
use clazel_tls::encode::{write_certificate, write_encrypted_extensions};
use clazel_tls::host::exec::Host;
use clazel_tls::transcript::exec::Transcript;
use clazel_tls::transcript::spec::Kind;
use clazel_tls::types::{Certificate, CertificateEntry};
use clazel_x509::path::parsed::exec::parse_path_cert;
use clazel_x509::spki::exec::{PublicKey, parse_subject_public_key_info};
use clazel_x509::time::exec::CertificateTime;

struct Case {
    id: &'static str,
    kind: &'static str,
    expected: &'static str,
    peer: (&'static str, &'static str),
    peer_names: &'static [(&'static str, &'static str)],
    time: &'static str,
    features: &'static [&'static str],
    importance: &'static str,
    max_chain_depth: Option<u32>,
    key_usage: &'static [&'static str],
    extended_key_usage: &'static [&'static str],
    trusted: &'static [usize],
    intermediates: &'static [usize],
    leaf: usize,
}

// `TESTCASE_COUNT`, `CERT_SPANS` and `CASES`, generated by clazel-x509.
include!("../../clazel-x509/tests/generated/x509_limbo.rs");

static CERTS: &[u8] = include_bytes!("../../clazel-x509/tests/generated/x509_limbo_certs.bin");

fn need<T>(value: Option<T>, what: &str) -> Result<T, String> {
    value.ok_or_else(|| what.to_owned())
}

fn limbo_cert(index: usize) -> Result<&'static [u8], String> {
    let &(offset, length) = need(CERT_SPANS.get(index), "certificate index")?;
    let start = usize::try_from(offset).map_err(|e| e.to_string())?;
    let end = start
        .checked_add(usize::try_from(length).map_err(|e| e.to_string())?)
        .ok_or("certificate span")?;
    need(CERTS.get(start..end), "certificate span")
}

/// Whether the testcase's key-usage and extended-key-usage expectations are
/// ones the profile always meets: digitalSignature, and serverAuth for a
/// server (the profile requires both whenever the certificate states them).
fn usage_expectations_are_the_profiles(case: &Case) -> bool {
    case.key_usage.iter().all(|k| *k == "digitalSignature")
        && case.extended_key_usage.iter().all(|e| *e == "serverAuth")
}

fn case(id: &str) -> Result<&'static Case, String> {
    assert_eq!(CASES.len(), TESTCASE_COUNT);
    let c = need(CASES.iter().find(|c| c.id == id), id)?;
    // A server testcase with one peer name (the host).
    assert_eq!(c.kind, "SERVER", "{id}");
    assert!(c.peer_names.is_empty(), "{id}");
    // The join builds the production environment: the default depth.
    assert!(
        c.max_chain_depth.is_none() && usage_expectations_are_the_profiles(c),
        "{id}"
    );
    Ok(c)
}

/// Seconds since 1970-01-01T00:00:00Z of a proleptic Gregorian date and
/// time (H. Hinnant's `days_from_civil`), for years 1970 to 9999.
fn unix(year: i64, month: i64, day: i64, hour: i64, minute: i64, second: i64) -> Option<u64> {
    let y = if month <= 2 {
        year.checked_sub(1)?
    } else {
        year
    };
    let era = y.checked_div(400)?;
    let yoe = y.checked_sub(era.checked_mul(400)?)?;
    let mp = month.checked_add(9)?.checked_rem(12)?;
    let doy = mp
        .checked_mul(153)?
        .checked_add(2)?
        .checked_div(5)?
        .checked_add(day)?
        .checked_sub(1)?;
    let doe = yoe
        .checked_mul(365)?
        .checked_add(yoe.checked_div(4)?)?
        .checked_sub(yoe.checked_div(100)?)?
        .checked_add(doy)?;
    let days = era
        .checked_mul(146_097)?
        .checked_add(doe)?
        .checked_sub(719_468)?;
    let seconds = days
        .checked_mul(86_400)?
        .checked_add(hour.checked_mul(3_600)?)?
        .checked_add(minute.checked_mul(60)?)?
        .checked_add(second)?;
    u64::try_from(seconds).ok()
}

fn unix_of(time: &CertificateTime) -> Option<u64> {
    unix(
        i64::from(time.year),
        i64::from(time.month),
        i64::from(time.day),
        i64::from(time.hour),
        i64::from(time.minute),
        i64::from(time.second),
    )
}

/// Limbo's validation time `YYYY-MM-DDTHH:MM:SS+00:00` in Unix seconds, or
/// one day after the leaf's notBefore when limbo gives none.
fn limbo_now(case: &Case) -> Result<u64, String> {
    if case.time.is_empty() {
        let leaf = need(parse_path_cert(limbo_cert(case.leaf)?), "leaf parses")?;
        let not_before = need(unix_of(&leaf.tbs.not_before), "leaf notBefore")?;
        return Ok(not_before.saturating_add(86_400));
    }
    let body = need(case.time.strip_suffix("+00:00"), case.time)?;
    let (date, clock) = need(body.split_once('T'), case.time)?;
    let number = |s: Option<&str>| -> Result<i64, String> {
        need(s, case.time)?
            .split('.')
            .next()
            .unwrap_or("")
            .parse::<i64>()
            .map_err(|e| e.to_string())
    };
    let mut d = date.split('-');
    let mut c = clock.split(':');
    need(
        unix(
            number(d.next())?,
            number(d.next())?,
            number(d.next())?,
            number(c.next())?,
            number(c.next())?,
            number(c.next())?,
        ),
        case.time,
    )
}

fn host_of(case: &Case) -> Result<Host, String> {
    match case.peer {
        ("DNS", name) => Ok(Host::Dns(name.as_bytes().to_vec())),
        ("IP", text) => match text
            .parse::<std::net::IpAddr>()
            .map_err(|e| e.to_string())?
        {
            std::net::IpAddr::V4(a) => Ok(Host::Ip(a.octets().to_vec())),
            std::net::IpAddr::V6(a) => Ok(Host::Ip(a.octets().to_vec())),
        },
        _ => Err(format!("{}: no peer name", case.id)),
    }
}

/// The verifier over a testcase's own trusted certificates.
fn limbo_verifier(case: &Case) -> Result<ChainVerifier<'static>, String> {
    let roots = case
        .trusted
        .iter()
        .map(|&i| {
            Ok(Root {
                der: limbo_cert(i)?,
                server_distrust_after: None,
            })
        })
        .collect::<Result<Vec<_>, String>>()?;
    Ok(ChainVerifier::new(&roots))
}

/// RFC 8446 §4.4.2: a Certificate body with these certificates, in order,
/// an empty context and no entry extensions.
fn body_of(certificates: &[&[u8]]) -> Vec<u8> {
    let value = Certificate {
        context: &[],
        entries: certificates
            .iter()
            .map(|cert_data| CertificateEntry {
                cert_data,
                extensions: Vec::new(),
            })
            .collect(),
    };
    let mut body = Vec::new();
    write_certificate(&mut body, &value);
    body
}

/// The leaf, then limbo's intermediates in order.
fn presented(case: &Case) -> Result<Vec<&'static [u8]>, String> {
    let mut certs = vec![limbo_cert(case.leaf)?];
    for &i in case.intermediates {
        certs.push(limbo_cert(i)?);
    }
    Ok(certs)
}

fn leaf_spki(case: &Case) -> Result<Vec<u8>, String> {
    let leaf = need(parse_path_cert(limbo_cert(case.leaf)?), "leaf parses")?;
    Ok(leaf.tbs.subject_public_key_info_der.to_vec())
}

fn validate(
    verifier: &ChainVerifier<'_>,
    case: &Case,
) -> Result<Result<Vec<u8>, CertificateError>, String> {
    Ok(verifier.validate(
        &host_of(case)?,
        limbo_now(case)?,
        &body_of(&presented(case)?),
    ))
}

/// Whether a trusted or intermediate certificate of `case` has a secp384r1
/// key: a link from it is refused until P17.
fn has_p384_ca(case: &Case) -> Result<bool, String> {
    for &i in case.trusted.iter().chain(case.intermediates) {
        let is_p384 = parse_path_cert(limbo_cert(i)?)
            .and_then(|c| parse_subject_public_key_info(c.tbs.subject_public_key_info_der))
            .is_some_and(|k| matches!(k.public_key, PublicKey::EcP384(_)));
        if is_p384 {
            return Ok(true);
        }
    }
    Ok(false)
}

#[test]
fn the_production_verifier_holds_all_118_mozilla_roots() {
    // `mozilla` is the one unverified step (it copies the table's rows);
    // `ChainVerifier::new` is proven to keep every row `anchor_from_root`
    // accepts, and all 118 are.
    assert_eq!(clazel_x509::roots::ROOTS.len(), 118);
    assert_eq!(mozilla().anchor_count(), 118);
}

#[test]
#[cfg_attr(miri, ignore)]
fn real_world_chains_validate_against_the_mozilla_roots() -> Result<(), String> {
    let production = mozilla();
    let mut accepted = Vec::new();
    let mut p384 = Vec::new();
    for c in CASES.iter().filter(|c| c.id.starts_with("online::")) {
        assert_eq!(
            (c.expected, c.kind),
            ("SUCCESS", "SERVER"),
            "{} {:?} {}",
            c.id,
            c.features,
            c.importance
        );
        match validate(&production, c)? {
            // The key returned is the leaf's SubjectPublicKeyInfo.
            Ok(key) => {
                assert_eq!(key, leaf_spki(c)?, "{}", c.id);
                accepted.push(c.id);
            }
            // A P-384 CA's link is refused until P17; the path search then
            // finds no valid path (BadSignature or UnknownIssuer: unknown_ca).
            Err(error) => {
                assert!(has_p384_ca(c)?, "{}: {error:?} without a P-384 CA", c.id);
                assert_eq!(error, CertificateError::UnknownCa, "{}", c.id);
                p384.push(c.id);
            }
        }
    }
    assert_eq!(
        accepted,
        [
            "online::bing.com",
            "online::fastly.com",
            "online::s3.amazonaws.com",
            "online::aws.amazon.com",
            "online::docs.python.org",
            "online::amazon.com",
            "online::facebook.com",
            "online::google.com",
            "online::storage.googleapis.com",
            "online::microsoft.com",
        ]
    );
    assert_eq!(
        p384,
        [
            "online::akamai.com",
            "online::apple.com",
            "online::cloudflare.com",
            "online::stackoverflow.com",
        ]
    );
    Ok(())
}

#[test]
fn an_empty_certificate_list_is_a_bad_certificate() {
    // RFC 8446 §4.4.2 requires the server's certificate first; with none,
    // `chain_inputs` is `Malformed` (bad_certificate). The auth machine
    // refuses such a body before validation (decode_error), below.
    let verifier = mozilla();
    let host = Host::Dns(b"google.com".to_vec());
    assert_eq!(
        verifier.validate(&host, 1_786_000_000, &body_of(&[])),
        Err(CertificateError::BadCertificate)
    );
}

#[test]
fn garbage_is_a_bad_certificate() -> Result<(), String> {
    let verifier = mozilla();
    let c = case("online::google.com")?;
    let host = host_of(c)?;
    let now = limbo_now(c)?;
    // A body that is not a Certificate.
    assert_eq!(
        verifier.validate(&host, now, &[0xff]),
        Err(CertificateError::BadCertificate)
    );
    // Trailing bytes after the certificate_list.
    let mut trailing = body_of(&presented(c)?);
    trailing.push(0);
    assert_eq!(
        verifier.validate(&host, now, &trailing),
        Err(CertificateError::BadCertificate)
    );
    // A leaf entry that is not DER.
    let intermediates = presented(c)?;
    let mut garbage_leaf: Vec<&[u8]> = vec![b"not a certificate"];
    garbage_leaf.extend_from_slice(intermediates.get(1..).unwrap_or(&[]));
    assert_eq!(
        verifier.validate(&host, now, &body_of(&garbage_leaf)),
        Err(CertificateError::BadCertificate)
    );
    // A garbage pool entry is dropped from the pool (design §2.6 step 3),
    // so the path through the real intermediate is still found. Not under
    // Miri: finding it verifies every signature of the chain, which took
    // over 300 s there (the tests above that validate whole chains are
    // ignored under Miri for the same reason); the refusals above stop
    // before any signature and still run.
    if !cfg!(miri) {
        let mut garbage_pool = presented(c)?;
        garbage_pool.insert(1, b"not a certificate either");
        assert_eq!(
            verifier.validate(&host, now, &body_of(&garbage_pool)),
            Ok(leaf_spki(c)?)
        );
    }
    Ok(())
}

#[test]
#[cfg_attr(miri, ignore)]
fn the_wrong_host_is_a_bad_certificate() -> Result<(), String> {
    let verifier = mozilla();
    let c = case("online::google.com")?;
    let body = body_of(&presented(c)?);
    let now = limbo_now(c)?;
    assert_eq!(
        verifier.validate(&Host::Dns(b"google.com".to_vec()), now, &body),
        Ok(leaf_spki(c)?)
    );
    // `Leaf`: the leaf's identity check fails (bad_certificate).
    for wrong in [
        &b"example.com"[..],
        b"oogle.com",
        b"google.com.evil.example",
    ] {
        assert_eq!(
            verifier.validate(&Host::Dns(wrong.to_vec()), now, &body),
            Err(CertificateError::BadCertificate),
            "{}",
            String::from_utf8_lossy(wrong)
        );
    }
    Ok(())
}

#[test]
#[cfg_attr(miri, ignore)]
fn an_expired_leaf_is_refused() -> Result<(), String> {
    // limbo: the leaf expired before the validation time. The search's
    // first candidate fails the leaf profile (`Leaf`, which covers the
    // leaf's validity): bad_certificate.
    let c = case("rfc5280::validity::expired-leaf")?;
    assert_eq!(c.expected, "FAILURE");
    assert_eq!(
        validate(&limbo_verifier(c)?, c)?,
        Err(CertificateError::BadCertificate)
    );
    // A real chain, ten years after limbo's validation time.
    let c = case("online::google.com")?;
    let later = limbo_now(c)?.saturating_add(10 * 365 * 86_400);
    assert_eq!(
        mozilla().validate(&host_of(c)?, later, &body_of(&presented(c)?)),
        Err(CertificateError::BadCertificate)
    );
    Ok(())
}

