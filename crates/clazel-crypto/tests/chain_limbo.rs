//! x509-limbo with real links: the production link verifier
//! (`clazel_crypto::chain::exec::CertificateLinks`) inside P8's verdict on
//! one candidate (`clazel_x509::path::exec::candidate_verdict`), the path
//! being limbo's chain as its descriptions draw it (as in
//! `clazel-x509`'s tests/path_process.rs). The full search is P9's.
//!
//! Each drawn testcase is judged twice, with links that accept everything
//! and with the real ones. The difference is exactly what the signatures
//! decide. The vendored corpus and its derived files are clazel-x509's
//! (`tests/data/x509-limbo/SOURCE.md` there); this crate depends on
//! clazel-x509, so `cargo xtask verify --changed` re-runs this test when
//! they change.

use std::net::IpAddr;

use clazel_crypto::chain::exec::CertificateLinks;
use clazel_x509::certificate::exec::AlgorithmIdentifier;
use clazel_x509::matcher::ReferenceIdentity;
use clazel_x509::path::contract::{LinkVerifier, RevocationOracle};
use clazel_x509::path::exec::{Candidate, Environment, candidate_verdict, chain_inputs};
use clazel_x509::path::parsed::exec::{Anchor, PathCert, anchor_from_root, parse_path_cert};
use clazel_x509::path::spec::PathError;
use clazel_x509::spki::exec::{PublicKey, parse_subject_public_key_info};
use clazel_x509::time::exec::CertificateTime;

/// Accepts every link.
struct AcceptAll;

impl LinkVerifier for AcceptAll {
    fn verify(&self, _: &[u8], _: &AlgorithmIdentifier<'_>, _: &[u8], _: &[u8]) -> bool {
        true
    }
}

/// Nothing is revoked (the production oracle).
struct NotRevoked;

impl RevocationOracle for NotRevoked {
    fn is_revoked(&self, _: &PathCert<'_>) -> bool {
        false
    }
}

struct Case {
    id: &'static str,
    kind: &'static str,
    expected: &'static str,
    peer: (&'static str, &'static str),
    peer_names: &'static [(&'static str, &'static str)],
    time: &'static str,
    features: &'static [&'static str],
    importance: &'static str,
    max_chain_depth: Option<u32>,
    key_usage: &'static [&'static str],
    extended_key_usage: &'static [&'static str],
    trusted: &'static [usize],
    intermediates: &'static [usize],
    leaf: usize,
}

// `TESTCASE_COUNT`, `CERT_SPANS` and `CASES`, generated by clazel-x509.
include!("../../clazel-x509/tests/generated/x509_limbo.rs");

static CERTS: &[u8] = include_bytes!("../../clazel-x509/tests/generated/x509_limbo_certs.bin");

/// Whether the testcase's key-usage and extended-key-usage expectations are
/// ones the profile always meets: digitalSignature, and serverAuth for a
/// server (the profile requires both whenever the certificate states them).
fn usage_expectations_are_the_profiles(case: &Case) -> bool {
    case.key_usage.iter().all(|k| *k == "digitalSignature")
        && case.extended_key_usage.iter().all(|e| *e == "serverAuth")
}

fn need<T>(value: Option<T>, what: &str) -> Result<T, String> {
    value.ok_or_else(|| what.to_owned())
}

fn limbo_cert(index: usize) -> Option<&'static [u8]> {
    let &(offset, length) = CERT_SPANS.get(index)?;
    let start = usize::try_from(offset).ok()?;
    let end = start.checked_add(usize::try_from(length).ok()?)?;
    CERTS.get(start..end)
}

/// `YYYY-MM-DDTHH:MM:SS+00:00`, fractional seconds truncated.
fn parse_time(text: &str) -> Option<CertificateTime> {
    let body = text.strip_suffix("+00:00")?;
    let (date, clock) = body.split_once('T')?;
    let mut d = date.split('-');
    let mut c = clock.split(':');
    let time = CertificateTime {
        year: d.next()?.parse().ok()?,
        month: d.next()?.parse().ok()?,
        day: d.next()?.parse().ok()?,
        hour: c.next()?.parse().ok()?,
        minute: c.next()?.parse().ok()?,
        second: c.next()?.split('.').next()?.parse().ok()?,
    };
    (d.next().is_none() && c.next().is_none()).then_some(time)
}

fn copy(time: &CertificateTime) -> CertificateTime {
    CertificateTime {
        year: time.year,
        month: time.month,
        day: time.day,
        hour: time.hour,
        minute: time.minute,
        second: time.second,
    }
}

/// Limbo's chain as drawn, judged with `link`: `None` when the case cannot
/// be drawn here (a leaf or chain that does not parse, no anchor by name,
/// an intermediate left out, or no single peer name).
fn limbo_verdict<L: LinkVerifier>(case: &Case, link: &L) -> Option<Result<(), PathError>> {
    if case.kind != "SERVER"
        || !case.peer_names.is_empty()
        || !usage_expectations_are_the_profiles(case)
    {
        return None;
    }
    let anchors: Vec<Anchor<'static>> = case
        .trusted
        .iter()
        .filter_map(|&i| anchor_from_root(limbo_cert(i)?, None))
        .collect();
    let mut presented: Vec<&[u8]> = vec![limbo_cert(case.leaf)?];
    for &i in case.intermediates {
        presented.push(limbo_cert(i)?);
    }
    let inputs = chain_inputs(&presented, 0).ok()?;
    let now = if case.time.is_empty() {
        copy(&inputs.leaf.tbs.not_before)
    } else {
        parse_time(case.time)?
    };
    // From the leaf, each issuer by name, a self-issued intermediate before
    // another of the same name, none twice (tests/path_process.rs).
    let mut path: Vec<usize> = Vec::new();
    let mut issuer = inputs.leaf.tbs.issuer_der;
    let anchor = loop {
        let issues = |j: usize, c: &Option<PathCert<'_>>, self_issued: bool| {
            !path.contains(&j)
                && c.as_ref().is_some_and(|c| {
                    c.tbs.subject_der == issuer
                        && (!self_issued || c.tbs.issuer_der == c.tbs.subject_der)
                })
        };
        let next = inputs
            .pool
            .iter()
            .enumerate()
            .position(|(j, c)| issues(j, c, true))
            .or_else(|| {
                inputs
                    .pool
                    .iter()
                    .enumerate()
                    .position(|(j, c)| issues(j, c, false))
            });
        if let Some(j) = next {
            path.insert(0, j);
            issuer = inputs.pool.get(j)?.as_ref()?.tbs.issuer_der;
            continue;
        }
        break anchors.iter().position(|a| a.subject_der == issuer)?;
    };
    if path.len() != case.intermediates.len() {
        return None;
    }
    let address;
    let reference = match case.peer {
        ("DNS", host) => ReferenceIdentity::Dns(host.as_bytes()),
        ("IP", text) => {
            address = match text.parse::<IpAddr>().ok()? {
                IpAddr::V4(a) => a.octets().to_vec(),
                IpAddr::V6(a) => a.octets().to_vec(),
            };
            ReferenceIdentity::Ip(&address)
        }
        _ => return None,
    };
    let environment = Environment {
        link,
        revoked: &NotRevoked,
        max_intermediates: case
            .max_chain_depth
            .map_or(6, |d| usize::try_from(d).unwrap_or(6)),
    };
    Some(
        candidate_verdict(
            &environment,
            &anchors,
            &inputs.pool,
            &inputs.leaf,
            &Candidate {
                anchor,
                path: &path,
            },
            reference,
            &now,
        )
        .map(|_| ()),
    )
}

/// Whether a trusted or intermediate certificate of `case` has a secp384r1
/// key: a link from it is refused until P17.
fn has_p384_ca(case: &Case) -> bool {
    case.trusted.iter().chain(case.intermediates).any(|&i| {
        limbo_cert(i)
            .and_then(parse_path_cert)
            .and_then(|c| parse_subject_public_key_info(c.tbs.subject_public_key_info_der))
            .is_some_and(|k| matches!(k.public_key, PublicKey::EcP384(_)))
    })
}

/// The signature-related testcases, with the verdict the real links give
/// (limbo's own expectation in the comment where it differs).
const SIGNATURE_CASES: &[(&str, Result<(), PathError>)] = &[
    ("invalid::invalid-issuer-key", Err(PathError::BadSignature)),
    (
        "webpki::forbidden-weak-rsa-key-in-root",
        Err(PathError::BadSignature),
    ),
    ("webpki::forbidden-p192-root", Err(PathError::BadSignature)),
    ("webpki::explicit-curve", Err(PathError::BadSignature)),
    (
        "webpki::forbidden-dsa-root",
        Err(PathError::UnsupportedAlgorithm),
    ),
    // limbo: FAILURE. Accepted, as Chrome, Firefox and webpki accept a
    // 2052-bit key (BR §6.1.5 asks for a multiple of 8): a listed divergence.
    ("webpki::forbidden-rsa-not-divisible-by-8-in-root", Ok(())),
];

#[test]
#[cfg_attr(miri, ignore)]
fn signature_related_cases_get_the_expected_verdict() -> Result<(), String> {
    assert_eq!(CASES.len(), TESTCASE_COUNT);
    let mut wrong = Vec::new();
    for (id, expected) in SIGNATURE_CASES {
        let case = need(CASES.iter().find(|c| c.id == *id), id)?;
        let verdict = need(limbo_verdict(case, &CertificateLinks), id)?;
        if verdict != *expected {
            wrong.push(format!("{id}: {verdict:?}, expected {expected:?}"));
        }
    }
    assert!(wrong.is_empty(), "{wrong:#?}");
    Ok(())
}

#[test]
#[cfg_attr(miri, ignore)]
fn limbo_links_sweep() -> Result<(), String> {
    let mut drawn = 0usize;
    let mut refused_by_links = Vec::new();
    let mut success_refused = Vec::new();
    let mut p384_refused = Vec::new();
    for (k, case) in CASES.iter().enumerate() {
        // Every non-BetterTLS case, and every 25th BetterTLS one.
        if case.id.starts_with("bettertls::") && k % 25 != 0 {
            continue;
        }
        let Some(fake) = limbo_verdict(case, &AcceptAll) else {
            continue;
        };
        let real = need(limbo_verdict(case, &CertificateLinks), case.id)?;
        drawn = drawn.saturating_add(1);
        if fake.is_ok() && real.is_err() {
            if case.expected == "FAILURE" {
                refused_by_links.push((case.id, real));
            } else if has_p384_ca(case) {
                p384_refused.push(case.id);
            } else {
                success_refused.push((case.id, case.features, case.importance, real));
            }
        } else if fake != real && real != Err(PathError::BadSignature) {
            // Real links only add BadSignature refusals; one may come first
            // (at an earlier certificate's (a)(1)), but nothing else changes.
            return Err(format!(
                "{}: {fake:?} with any link, {real:?} with ours",
                case.id
            ));
        }
    }
    println!(
        "limbo: {drawn} testcases drawn; FAILURE refused by the links alone: {refused_by_links:#?}"
    );
    println!("limbo: SUCCESS refused, a P-384 CA key (P17): {p384_refused:?}");
    // No SUCCESS testcase is refused by the links except through a P-384
    // key, which is refused until P17 (an expected failure).
    assert!(success_refused.is_empty(), "{success_refused:#?}");
    assert_eq!(
        p384_refused,
        [
            "online::akamai.com",
            "online::apple.com",
            "online::cloudflare.com",
            "online::stackoverflow.com",
        ]
    );
    Ok(())
}
