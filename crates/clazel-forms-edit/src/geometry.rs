//! The editor's [`Geometry`] over a laid-out document: hit testing and
//! text positions from `clazel-layout` (phase-6.md item 6.15).

use clazel_dom::exec::Arena;
use clazel_layout::boxes::{BoxTree, StyleFns};
use clazel_layout::controls::{self, ControlView};
use clazel_layout::flow::style::box_styles;
use clazel_layout::flow::{FragmentTree, TextFns};
use clazel_style::cascade::computed::ComputedStyle;

use crate::editor::Geometry;

/// 1px in the fragment tree's 1/64 px.
const PX: i32 = 64;

/// A laid-out document as the editor's geometry.
pub struct LayoutGeometry<'a, T: TextFns> {
    frags: &'a FragmentTree,
    tree: &'a BoxTree,
    arena: &'a Arena,
    fonts: &'a T,
    styles: Vec<ComputedStyle>,
}

impl<'a, T: TextFns> LayoutGeometry<'a, T> {
    /// The geometry of `frags`, the layout of `tree` (built from `arena`
    /// with computed style `styles`) in `fonts`.
    pub fn new(
        frags: &'a FragmentTree,
        tree: &'a BoxTree,
        arena: &'a Arena,
        styles: &impl StyleFns,
        fonts: &'a T,
    ) -> Self {
        LayoutGeometry {
            frags,
            tree,
            arena,
            fonts,
            styles: box_styles(tree, styles),
        }
    }

    /// The box generated by `node` and its border box.
    fn of(&self, node: usize) -> Option<(usize, clazel_layout::flow::Rect)> {
        let b = (0..self.tree.boxes.len()).find(|&b| self.frags.node(b) == Some(node))?;
        Some((b, self.frags.fragment(b)?.border_box))
    }
}

impl<T: TextFns> Geometry for LayoutGeometry<'_, T> {
    fn node_at(&self, x: i32, y: i32) -> Option<usize> {
        controls::node_at(
            self.frags,
            self.tree,
            x.saturating_mul(PX),
            y.saturating_mul(PX),
        )
    }

    fn caret_at(&self, view: &ControlView, x: i32, y: i32) -> Option<usize> {
        let (b, bb) = self.of(view.node)?;
        let style = self.styles.get(b)?;
        Some(controls::caret_at(
            view,
            self.arena,
            style,
            self.fonts,
            bb,
            x.saturating_mul(PX),
            y.saturating_mul(PX),
        ))
    }

    fn option_at(&self, view: &ControlView, x: i32, y: i32) -> Option<usize> {
        let (b, bb) = self.of(view.node)?;
        let style = self.styles.get(b)?;
        let (fx, fy) = (x.saturating_mul(PX), y.saturating_mul(PX));
        if fx < bb.x || fx >= bb.right() {
            return None;
        }
        controls::option_at(
            self.arena,
            view.node,
            &view.selected,
            style,
            self.fonts,
            bb,
            fy,
        )
    }
}
