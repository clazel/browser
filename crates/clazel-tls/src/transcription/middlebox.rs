//! RFC 8446 Appendix D.4, middlebox compatibility mode, on the client's sending
//! side, with §4.1.2's `legacy_session_id` and §5's change_cipher_spec record;
//! and the client's configuration that selects it and names the host (RFC 6066
//! §3, in [`server_name`](super::server_name)).
//!
//! This is the client as the application starts it: [`ClientConfig`] says what
//! it connects to and in which mode, [`client_hello_conforms_for`] what its first
//! ClientHello must hold for that, and [`start_client`] and
//! [`client_receive_stream`] are `connection::start_connection` and
//! `connection::receive_stream` with D.4's dummy record added where D.4 puts it.
//!
//! Modelling choices:
//! - **Compatibility mode is a parameter**, [`ClientConfig::compatibility_mode`].
//!   D.4 makes it optional ("Implementations can increase the chance ... This
//!   'compatibility mode' is partially negotiated: the client can opt to provide
//!   a session ID or not"). With it on, the client does all D.4 asks of it;
//!   with it off, none of it.
//! - **legacy_session_id.** §4.1.2: "In compatibility mode (see Appendix D.4),
//!   this field MUST be non-empty, so a client not offering a pre-TLS 1.3
//!   session MUST generate a new 32-byte value ... Otherwise, it MUST be set as a
//!   zero-length vector". The client offers no pre-TLS 1.3 session (it offers
//!   TLS 1.3 only, `key_exchange::client_hello_conforms`), so the field is 32
//!   bytes in the mode and empty outside it. The value is the caller's ("need not
//!   be random but SHOULD be unpredictable"), like `random`.
//! - **Which dummy records, and when.** D.4: "If not offering early data, the
//!   client sends a dummy change_cipher_spec record (see the third paragraph of
//!   Section 5) immediately before its second flight. This may either be before
//!   its second ClientHello or before its encrypted handshake flight." The
//!   client never offers early data. "a dummy change_cipher_spec record" is one
//!   record, and "its second flight" is the first flight after the first
//!   ClientHello: after a HelloRetryRequest that is the second ClientHello, and
//!   otherwise the encrypted flight (the empty Certificate if one was requested,
//!   and Finished). So one record, before whichever of the two comes first, and
//!   none before the encrypted flight after a HelloRetryRequest. The sentence
//!   "This may either be before its second ClientHello or before its encrypted
//!   handshake flight" is read as naming those two cases, not as a choice within
//!   one. See the PR's proposed errata.
//! - **What "before its second flight" means in records**: every record the
//!   client writes in the handshake after its first ClientHello belongs to its
//!   second flight (the second ClientHello, or the encrypted flight). So the
//!   dummy record is put immediately before the first record the client writes
//!   after its first ClientHello, and never again. Alerts are not a flight: an
//!   abort writes `connection::abort_record`, never preceded by the dummy record.
//! - **The record.** §5: "an unencrypted record of type change_cipher_spec
//!   consisting of the single byte value 0x01". It is a TLSPlaintext even when
//!   K_send is engaged, since a protected one must be rejected ("which receives a
//!   protected change_cipher_spec record MUST abort"), and its
//!   legacy_record_version is 0x0303: §5.1, "MUST be set to 0x0303 for all
//!   records generated by a TLS 1.3 implementation other than an initial
//!   ClientHello". It is outside the transcript (§4.4.1 lists handshake messages)
//!   and does not use a sequence number (§5.3 counts protected records; see
//!   `connection`'s modelling choices).
//! - **The server's side of D.4** ("if the client sends a non-empty session ID,
//!   the server MUST send the change_cipher_spec") gives the client nothing to
//!   check: §5 says to drop such a record, and no text says what to do if it is
//!   missing. Receiving is `connection::receive_record`'s, unchanged.
//! - `connection`'s own header says its sender sends no dummy change_cipher_spec.
//!   That is still so of `connection`; the record is added here, around it.
//! - After the handshake the wrapper adds nothing: application data, KeyUpdate
//!   and closure are `connection`'s functions on [`ClientConnection::connection`].
//! - After our close_notify (`connection::close_write_side`), `connection` writes no
//!   handshake record, so [`before_second_flight`] adds no dummy record either: it
//!   puts one only before a record the client writes. §6.1's close_notify says "the
//!   sender will not send any more messages on this connection".

